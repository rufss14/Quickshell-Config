#!/usr/bin/env bash
# ══════════════════════════════════════════════
#  wal-reload.sh
#  Reads pywal's colors.json, merges the colours edited in Quickshell's colour
#  panel (theming/pywal-overrides.json), writes palette.lua, and reloads Hyprland.
#
#  Which wal index each role (active border / inactive border / shadow) uses is
#  set in ~/.config/hypr/blend.lua — the file this config shares with Quickshell.
#
#  @QUICKSHELL_DIR@ is rewritten by scripts/install-hypr-config.sh.
#
#  Usage:
#    ./wal-reload.sh             # reads ~/.cache/wal/colors.json
#    ./wal-reload.sh <image>     # runs `wal -i <image>` first, then reloads
#    ./wal-reload.sh --live      # palette.lua, then the three colours set at
#                                # RUNTIME — no `hyprctl reload`
#
#  --live is what the shell's theming fan-out uses (scripts/reload-theme.sh).
#  palette.lua only feeds three values (appearance.lua: the two border colours and
#  the shadow), and a full `hyprctl reload` to deliver them re-ran the whole Lua
#  config after every wallpaper/colour change: ~100ms here, a compositor hitch right
#  after the wave landed, and a `configreloaded` that made the shell re-apply the
#  cursor, the cursor plugin and the wave's layer rule. `hyprctl eval` of the same
#  hl.config is ~5ms and touches nothing else (measured 2026-10-01). palette.lua is
#  still written, so the next start reads the same colours. If the eval is refused
#  (an older Hyprland), it falls back to the reload.
# ══════════════════════════════════════════════
set -euo pipefail

HYPR_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/hypr"
CACHE="${XDG_CACHE_HOME:-$HOME/.cache}"
WAL_JSON="$CACHE/wal/colors.json"
# QS_OVERRIDES: the shell passes its own path when it runs the repo's copy, whose
# placeholder is never rewritten.
OVERRIDES="${QS_OVERRIDES:-@QUICKSHELL_DIR@/theming/pywal-overrides.json}"
OUT="$HYPR_DIR/palette.lua"

LIVE=0
[[ "${1:-}" == "--live" ]] && { LIVE=1; shift; }

if [[ -n "${1:-}" ]]; then
    # --cols16 is pywal16 (AUR); plain python-pywal (repo) doesn't know it.
    wal -i "$1" --cols16 -n -q 2>/dev/null \
        || wal -i "$1" -n -q \
        || { echo "wal failed" >&2; exit 1; }
fi
[[ -f "$WAL_JSON" ]] || { echo "No $WAL_JSON. Run: wal -i <image>" >&2; exit 1; }

# ── Role → wal index, from blend.lua ────────────
mapfile -t IDX < <(lua5.4 -e '
    local d = os.getenv("XDG_CONFIG_HOME") or (os.getenv("HOME") .. "/.config")
    local b = dofile(d .. "/hypr/blend.lua")
    print(b.border_active_wal); print(b.border_inactive_wal); print(b.shadow_wal)
')

# ── Merge overrides, and every value, in ONE jq ─
# (It was eleven jq processes.) Eleven lines out: wal_color0..7, then the three roles,
# each already `rgba(rrggbbff)`. Only a real #rrggbb gets through — these land in Lua
# the compositor runs: an override that isn't one is skipped (as merge-overrides.py
# does), and a palette slot that isn't one stops the script before a file is written.
[[ -f "$OVERRIDES" ]] || OVERRIDES=/dev/null
mapfile -t V < <(jq -rs --argjson idx "[${IDX[0]:-4},${IDX[1]:-2},${IDX[2]:-0}]" '
    (.[0].colors + ((.[1] // {}).colors // {}
        | with_entries(select(.value | type == "string" and test("^#[0-9a-fA-F]{6}$"))))) as $c
    | ([range(0;8)] + $idx)[]
    | $c["color\(.)"] // ""
    | if test("^#[0-9a-fA-F]{6}$") then "rgba(\(.[1:])ff)" else "BAD" end
' "$WAL_JSON" "$OVERRIDES")
if (( ${#V[@]} != 11 )) || printf '%s\n' "${V[@]}" | grep -qx BAD; then
    echo "palette has a slot that isn't #rrggbb — palette.lua left as it was" >&2
    exit 1
fi

cat > "$OUT.new" <<LUAEOF
-- ══════════════════════════════════════════════
--  palette.lua — auto-generated by scripts/wal-reload.sh
--  Do not edit by hand; run wal-reload.sh instead.
--  Which wal index maps to which role is set in blend.lua.
-- ══════════════════════════════════════════════

wal_color0 = "${V[0]}"
wal_color1 = "${V[1]}"
wal_color2 = "${V[2]}"
wal_color3 = "${V[3]}"
wal_color4 = "${V[4]}"
wal_color5 = "${V[5]}"
wal_color6 = "${V[6]}"
wal_color7 = "${V[7]}"

border_active   = "${V[8]}"
border_inactive = "${V[9]}"
shadow_color    = "${V[10]}"
LUAEOF
mv -f "$OUT.new" "$OUT"

echo "palette.lua updated."

# The instance this shell runs under; the newest one only when there's none.
if [[ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
    HYPRLAND_INSTANCE_SIGNATURE="$(ls -t "${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/hypr/" 2>/dev/null | head -1 || true)"
fi
export HYPRLAND_INSTANCE_SIGNATURE
if [[ -z "$HYPRLAND_INSTANCE_SIGNATURE" ]] || ! command -v hyprctl &>/dev/null; then
    echo "Hyprland not running or instance not found." >&2
    exit 0
fi
if [[ "$LIVE" == 1 ]] && hyprctl eval "hl.config({ general = { col = { active_border = \"${V[8]}\", inactive_border = \"${V[9]}\" } }, decoration = { shadow = { color = \"${V[10]}\" } } })" >/dev/null 2>&1; then
    echo "Hyprland recoloured live."
else
    hyprctl reload >/dev/null 2>&1
    echo "Hyprland reloaded."
fi
