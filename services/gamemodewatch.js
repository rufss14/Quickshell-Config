// ── gamemodewatch.js ──────────────────────────────────────────────────────────
// The protocol half of Gamemode's "follow games": which processes gamemoded says are
// registered, read off `gdbus monitor` and `ListGames`, plus what the profile regions
// in gamemode.ini ask for. Out of QML so it can be tested against gdbus's REAL output
// (`bun scripts/test-gamemodewatch.js`), captured from gamemode 1.8.2 here:
//
//   The name com.feralinteractive.GameMode is owned by :1.58
//   /com/feralinteractive/GameMode: com.feralinteractive.GameMode.GameRegistered (11340, objectpath '/com/feralinteractive/GameMode/Games/11340')
//   /com/feralinteractive/GameMode: org.freedesktop.DBus.Properties.PropertiesChanged ('com.feralinteractive.GameMode', {'ClientCount': <1>}, @as [])
//   /com/feralinteractive/GameMode: com.feralinteractive.GameMode.GameUnregistered (11340, objectpath '/com/feralinteractive/GameMode/Games/11340')
//   ListGames → ([(11340, objectpath '/com/feralinteractive/GameMode/Games/11340')],)
//
// ── Why PIDs and not ClientCount ──────────────────────────────────────────────
// ClientCount counts the shell's OWN gamemoderun hold as a client, so it cannot answer
// "is a game running" — and a hold that is killed rather than exiting stays counted
// until gamemoded's reaper notices, up to five seconds later. Tracking PIDs, minus the
// hold's, answers the real question.
// ─────────────────────────────────────────────────────────────────────────────

// One `gdbus monitor` line → an event, or null for anything else.
//   { kind: "registered" | "unregistered", pid }
//   { kind: "owner", owned }     gamemoded (dis)appeared on the bus
function parseMonitorLine(line) {
    const s = String(line ?? "")
    let m = s.match(/\.GameRegistered \((\d+),/)
    if (m) return { kind: "registered", pid: parseInt(m[1], 10) }
    m = s.match(/\.GameUnregistered \((\d+),/)
    if (m) return { kind: "unregistered", pid: parseInt(m[1], 10) }
    // gdbus's own wording (gio/gdbus-tool.c, on_name_appeared / on_name_vanished).
    if (/^The name com\.feralinteractive\.GameMode is owned by /.test(s))
        return { kind: "owner", owned: true }
    if (/^The name com\.feralinteractive\.GameMode does not have an owner/.test(s))
        return { kind: "owner", owned: false }
    return null
}

// `gdbus call … ListGames` output → the registered PIDs.
function parseListGames(text) {
    const out = []
    const re = /\((\d+), objectpath /g
    let m
    while ((m = re.exec(String(text ?? ""))) !== null) out.push(parseInt(m[1], 10))
    return out
}

// The registered GAME PIDs after one event. Never mutates `pids` — the service
// assigns the result, and an in-place edit would fire no change signal.
// `ownPid` is the shell's own hold: registered like a game, never one.
function apply(pids, ev, ownPid) {
    if (!ev) return pids
    if (ev.kind === "registered") {
        if (ev.pid === ownPid || pids.indexOf(ev.pid) !== -1) return pids
        return pids.concat([ev.pid])
    }
    if (ev.kind === "unregistered")
        return pids.indexOf(ev.pid) === -1 ? pids : pids.filter(p => p !== ev.pid)
    // gamemoded went away: whatever it had registered, it no longer has.
    if (ev.kind === "owner" && !ev.owned) return pids.length === 0 ? pids : []
    return pids
}

// A seed from ListGames replaces the set — it is the daemon's own answer, not a delta.
function seed(listed, ownPid) {
    return listed.filter((p, i) => p !== ownPid && listed.indexOf(p) === i)
}

// ── The profile regions scripts/gamemode-profile.py writes ────────────────────
// The markers are that script's BEGIN / END, verbatim. What is read back is only what
// the panel shows; the file is the source of truth and nothing here writes it.
const BEGIN = "; quicktest:gamemode — generated by scripts/gamemode-profile.py, edits overwritten"
const END = "; end quicktest:gamemode"

// → { installed, renice, gpuLevel }. renice 0 / gpuLevel "" = not asked for.
function parseProfile(text) {
    const lines = String(text ?? "").split("\n")
    const b = lines.indexOf(BEGIN)
    if (b === -1) return { installed: false, renice: 0, gpuLevel: "" }
    let renice = 0, gpuLevel = ""
    for (let i = b + 1; i < lines.length && lines[i] !== END; i++) {
        let m = lines[i].match(/^\s*renice\s*=\s*(\d+)\s*$/)
        if (m) renice = parseInt(m[1], 10)
        m = lines[i].match(/^\s*amd_performance_level\s*=\s*(\w+)\s*$/)
        if (m) gpuLevel = m[1]
    }
    return { installed: true, renice: renice, gpuLevel: gpuLevel }
}

// ── What to call the game, and whether a Steam window is one ──────────────────
// Best effort, and said so in the panel: gamemoded registers a PID, not a title.
//
// A Steam game's window wears the class `steam_app_<id>` (Proton or native alike); Steam's own
// client is `steam`, which does NOT match. That class is a statement nothing but a Steam game
// makes, so it is the second trigger for "follow games" (Config.gamemodeSteam) — unlike
// "something is fullscreen", which a video player or a browser says just as loudly.
var STEAM_CLASS = /^steam_app_\d+$/

// The windows (Hypr.windows rows) that are Steam games.
function steamWindows(windows) {
    var out = []
    var list = windows || []
    for (var i = 0; i < list.length; i++)
        if (STEAM_CLASS.test(String((list[i] && list[i].appClass) || ""))) out.push(list[i])
    return out
}

// Names of processes that say nothing about the game: the Proton/Wine plumbing around it, the
// shell's own hold, launchers. A registered PID is often one of these when the game is Proton.
var GENERIC_COMM = /^(wine(64)?(-preloader)?|wineserver|reaper|proton|pressure-vessel.*|srt-.*|bwrap|steam.*|gamemoderun|gamescope.*|mangohud|env|timeout|python3?.*|sh|bash|cat|tini)$/i

// A process name as a game's name: ".exe" and "-bin" dropped, "" for the generic ones.
function tidyComm(comm) {
    var s = String(comm || "").trim().replace(/\.exe$/i, "").replace(/-(bin|wrapped)$/i, "")
    return s === "" || GENERIC_COMM.test(s) ? "" : s
}

// `steamTitles` — what the caller resolved for each Steam window, in order (the focused one
// first is the caller's call); `comms` — /proc/<pid>/comm of each registered PID. A Steam title
// wins (it is the game's real name); else the first process name that is not plumbing.
function labelFor(steamTitles, comms) {
    var t = steamTitles || []
    for (var i = 0; i < t.length; i++) if (String(t[i] || "").trim() !== "") return String(t[i]).trim()
    var c = comms || []
    for (var j = 0; j < c.length; j++) {
        var name = tidyComm(c[j])
        if (name !== "") return name
    }
    return ""
}

// `sh -c 'for p; …'` output ("<pid> <comm>" a line) → comms in the PIDs' order, "" where one
// has gone.
function parseComms(text, pids) {
    var byPid = {}
    var lines = String(text || "").split("\n")
    for (var i = 0; i < lines.length; i++) {
        var m = /^(\d+) (.*)$/.exec(lines[i])
        if (m) byPid[m[1]] = m[2]
    }
    return (pids || []).map(function (p) { return byPid[String(p)] || "" })
}

// The Steam app id in a `steam_app_<id>` class, "" for anything else. Native Linux games do NOT wear
// this class (Hollow Knight: Silksong's is "Hollow Knight Silksong"), which is why the class alone was an
// unreliable trigger: scripts/gamemode-steam.py reads the id from the process's own environment instead.
function steamAppId(cls) {
    var m = /^steam_app_(\d+)$/.exec(String(cls || ""))
    return m ? m[1] : ""
}

// ── Session history ───────────────────────────────────────────────────────────
// What the History page lists: one row per session the mode ran for at least a minute, newest first.
// { start (epoch ms), seconds, game ("" = unknown), appId ("" = not a Steam game), auto (it followed a game) }.
// Kept in gamemode-sessions.json (the state dir); hand-editable, so what is read back is cleaned.
var MIN_SESSION = 60
var MAX_SESSIONS = 60

// The list with `s` added at the front (a NEW list; a session shorter than a minute is not worth a row).
// A picture path kept with a row: an absolute path, no control characters, bounded. "" otherwise.
function _artPath(p) {
    return typeof p === "string" && p.length < 400 && p.charAt(0) === "/" && !/[\u0000-\u001f]/.test(p) ? p : ""
}

function addSession(list, s, max) {
    var base = Array.isArray(list) ? list : []
    if (!s || !(s.seconds >= MIN_SESSION) || !(s.start > 0)) return base
    var row = { start: Math.round(s.start), seconds: Math.round(s.seconds), game: String(s.game || "").slice(0, 80),
                appId: /^\d{1,10}$/.test(String(s.appId || "")) ? String(s.appId) : "", art: _artPath(s.art), auto: s.auto === true }
    return [row].concat(base).slice(0, Math.max(1, max || MAX_SESSIONS))
}

// Whatever came off disk → well-formed rows only, newest first, capped.
function cleanSessions(raw) {
    var list = raw && Array.isArray(raw.sessions) ? raw.sessions : []
    var out = []
    for (var i = 0; i < list.length; i++) {
        var s = list[i]
        if (!s || typeof s !== "object" || !(s.seconds >= MIN_SESSION) || !(s.start > 0)) continue
        out.push({ start: Math.round(s.start), seconds: Math.round(s.seconds), game: typeof s.game === "string" ? s.game.slice(0, 80) : "",
                   appId: /^\d{1,10}$/.test(String(s.appId || "")) ? String(s.appId) : "", art: _artPath(s.art), auto: s.auto === true })
    }
    out.sort(function (a, b) { return b.start - a.start })
    return out.slice(0, MAX_SESSIONS)
}

// "Today 18:20", "Yesterday 09:05", "Mon 21:40" (within the last week), "3 Nov" beyond.
var _DAYS = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
var _MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
function whenLabel(ms, now) {
    var d = new Date(ms), n = new Date(now)
    var hm = (d.getHours() < 10 ? "0" : "") + d.getHours() + ":" + (d.getMinutes() < 10 ? "0" : "") + d.getMinutes()
    var days = Math.round((new Date(n.getFullYear(), n.getMonth(), n.getDate()) - new Date(d.getFullYear(), d.getMonth(), d.getDate())) / 86400000)
    if (days <= 0) return "Today " + hm
    if (days === 1) return "Yesterday " + hm
    if (days < 7) return _DAYS[d.getDay()] + " " + hm
    return d.getDate() + " " + _MONTHS[d.getMonth()]
}
