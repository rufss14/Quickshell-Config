#!/usr/bin/env python3
"""Give Feral GameMode a real performance profile.

    gamemode-profile.py install [--system]    write (or refresh) the profile region
    gamemode-profile.py remove  [--system]    take the region out again
    gamemode-profile.py show    [--system]    print what install WOULD write

The Gaming panel's "Set up" / "Remove" buttons run this. Without config, gamemoded
does almost nothing on this kind of machine: it moves the CPU governor and stops
there — no GPU clocks, no priority — because both need to be asked for.

── Two files, because gamemode itself insists ────────────────────────────────
gamemoded refuses the [gpu] section from any config file a user can write ("The
[gpu] config section is not configurable from unsafe config files! … Consider
moving this option to /etc/gamemode.ini" — its own words, from the binary). Its
helper runs as root through polkit, so a user file overclocking the card would be a
privilege boundary with a hole in it. So:

  (user)      $XDG_CONFIG_HOME/gamemode.ini   [general] — no root needed
      renice=N   games run at nice -N. N is what this session may actually use: the
                 RLIMIT_NICE gamemode's own limits.d grants its group (usually 10).
                 Asking for more fails silently in gamemoded, so it is derived,
                 never assumed. 0 = not permitted here, and not written.
      ioprio=0   best-effort class, top level. gamemode's default, stated so the
                 region says everything it does.

  (--system)  /etc/gamemode.ini                [gpu] — needs root (sudo / pkexec)
      amd_performance_level=high   amdgpu DPM pinned to its top state for the
                 session, restored when the last game exits. Only for an amdgpu
                 card. `apply_gpu_optimisations=accept-responsibility` is the
                 keyphrase gamemode requires before it touches a GPU at all —
                 running `install --system` IS accepting it, which is why this is a
                 button the user presses, never something the shell does alone.

── Surgical, like generate-mangohud-config ───────────────────────────────────
Either file may be hand-written. This owns exactly one marked region per file,
appended at the end so its keys win (gamemode applies the last assignment of a
key), and keeps every other line as it was. `remove` gives the file back as it was
before `install` — and deletes it if the region was all there was.

The card is found from sysfs, never assumed: this machine's GPU is card1, not card0.

Exit codes: 0 done (or nothing to do), 2 usage, 3 no amdgpu card for --system,
4 --system without root.
"""

import os
import re
import resource
import subprocess
import sys
import tempfile

CONFIG = os.environ.get("XDG_CONFIG_HOME") or os.path.expanduser("~/.config")
USER_CONF = os.path.join(CONFIG, "gamemode.ini")
SYSTEM_CONF = "/etc/gamemode.ini"

BEGIN = "; quicktest:gamemode — generated by scripts/gamemode-profile.py, edits overwritten"
END = "; end quicktest:gamemode"


# ── Facts about this machine ──────────────────────────────────────────────────
def find_amd_gpu(sysfs="/sys"):
    """The DRM card number gamemode's gpu_device wants, or None.

    Only amdgpu cards that expose the DPM knob count. Several (an APU's iGPU beside a
    discrete card) → the one with the most VRAM, which is the one games run on."""
    drm = os.path.join(sysfs, "class", "drm")
    best, best_vram = None, -1
    try:
        names = os.listdir(drm)
    except OSError:
        return None
    for name in names:
        m = re.fullmatch(r"card(\d+)", name)
        if not m:
            continue
        dev = os.path.join(drm, name, "device")
        if os.path.basename(os.path.realpath(os.path.join(dev, "driver"))) != "amdgpu":
            continue
        if not os.path.exists(os.path.join(dev, "power_dpm_force_performance_level")):
            continue
        try:
            vram = int(open(os.path.join(dev, "mem_info_vram_total")).read().strip())
        except (OSError, ValueError):
            vram = 0
        if vram > best_vram:
            best, best_vram = int(m.group(1)), vram
    return best


def renice_for(nice_rlimit):
    """RLIMIT_NICE → the renice value gamemode may use. The limit's ceiling is
    20 - rlim, so 30 permits nice -10; gamemode takes the magnitude. Capped at 10:
    past that a game can starve the compositor it draws through."""
    return max(0, min(10, int(nice_rlimit) - 20))


# ── The regions ───────────────────────────────────────────────────────────────
def user_region(renice):
    out = [BEGIN,
           "; Priority for games. The GPU half lives in /etc/gamemode.ini (gamemode",
           "; ignores [gpu] in user files). Remove: scripts/gamemode-profile.py remove",
           "[general]"]
    if renice > 0:
        out.append("renice=%d" % renice)
    else:
        out.append("; renice left at 0: this session may not lower nice values"
                   " (see gamemode's limits.d)")
    out += ["ioprio=0", END]
    return out


def system_region(gpu):
    return [BEGIN,
            "; GPU clocks for games. Remove: sudo scripts/gamemode-profile.py remove --system",
            "[gpu]",
            "apply_gpu_optimisations=accept-responsibility",
            "gpu_device=%d" % gpu,
            "amd_performance_level=high",
            END]


def strip_region(lines):
    """`lines` without the region, and without the one blank line install put
    before it. An unterminated region (END deleted by hand) runs to the end."""
    try:
        b = lines.index(BEGIN)
    except ValueError:
        return lines, False
    try:
        e = lines.index(END, b)
    except ValueError:
        e = len(lines) - 1
    if b > 0 and lines[b - 1] == "":
        b -= 1
    return lines[:b] + lines[e + 1:], True


def install_text(text, region):
    """The file with `region` (re)written at the end. The only line added besides
    the region is the one blank separator, which strip_region takes back — so
    remove_text(install_text(t, r)) == t for any t that ends in a newline."""
    body, _ = strip_region(text.split("\n") if text else [])
    if body and body[-1] == "":
        body = body[:-1]            # the final newline, not a blank line
    return "\n".join(body + ([""] if body else []) + region) + "\n"


def remove_text(text):
    lines, found = strip_region(text.split("\n"))
    body = "\n".join(lines)
    return (body if body.strip() else ""), found


# ── Side effects ──────────────────────────────────────────────────────────────
def write_atomic(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".gamemode.ini.")
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)            # gamemoded reads it as the user, /etc included
    os.replace(tmp, path)


def refresh_daemon():
    """Ask a running gamemoded to re-read its config now. Best effort: it also
    watches its config files itself. Never as root: under pkexec or sudo there is no
    session bus of the user's to ask — gdbus would try to AUTOLAUNCH one, as root —
    so the caller (the shell, system-tune.sh) asks as the user instead."""
    if os.geteuid() == 0:
        return
    try:
        subprocess.run(["gdbus", "call", "--session",
                        "--dest", "com.feralinteractive.GameMode",
                        "--object-path", "/com/feralinteractive/GameMode",
                        "--method", "com.feralinteractive.GameMode.RefreshConfig"],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=5)
    except (OSError, subprocess.SubprocessError):
        pass


def main(argv):
    args = [a for a in argv if a != "--system"]
    system = len(args) != len(argv)
    cmd = args[0] if len(args) == 1 else ""
    if cmd not in ("install", "remove", "show"):
        sys.stderr.write(__doc__.split("\n\n")[0] + "\n")
        sys.stderr.write("usage: gamemode-profile.py install|remove|show [--system]\n")
        return 2

    if system:
        path = SYSTEM_CONF
        gpu = find_amd_gpu()
        if gpu is None and cmd != "remove":
            sys.stderr.write("gamemode-profile: no amdgpu card with DPM control — "
                             "nothing for the GPU half to do\n")
            return 3
        region = system_region(gpu) if gpu is not None else []
    else:
        path = USER_CONF
        region = user_region(renice_for(resource.getrlimit(resource.RLIMIT_NICE)[0]))

    if cmd == "show":
        sys.stdout.write("\n".join(region) + "\n")
        return 0
    if system and os.geteuid() != 0:
        sys.stderr.write("gamemode-profile: --system writes %s and needs root "
                         "(sudo or pkexec)\n" % SYSTEM_CONF)
        return 4

    try:
        text = open(path).read()
    except FileNotFoundError:
        text = None

    if cmd == "install":
        write_atomic(path, install_text(text or "", region))
    else:
        if text is None:
            return 0
        new, found = remove_text(text)
        if not found:
            return 0
        if new == "":
            os.remove(path)
        else:
            write_atomic(path, new)
    refresh_daemon()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
