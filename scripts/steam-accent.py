#!/usr/bin/env python3
# ── steam-accent.py ──────────────────────────────────────────────────────────
# Recolours the parts of Steam the theme can't reach. simply-dark exposes only its greys as
# variables; everything else Steam paints — the blue tab underline, the green buttons, the navy
# "What's New" panel, the slate text — is a LITERAL in Steam's own compiled stylesheets, so no
# variable pushed into a window can change it (measured on the live client: ~150 elements in
# Steam's blues, a 514x895 navy panel of #22242a). This module turns those literals into an
# override stylesheet in the palette's colours.
#
# Not a CLI. steam-live.py scans the running Steam for the rules (steam-scan.js) and keeps them in
# a cache. Two outputs, split so a wallpaper change never re-sends a megabyte:
#   · `rules_css`   the STATIC stylesheet: every declaration reads `var(--qs-<colour>)`, selectors
#                   sharing a declaration block are grouped. Depends only on the scan, never on
#                   the palette — so it is written (to Millennium's Quick CSS, which injects it
#                   into every window as it loads) and injected live only when Steam changes.
#   · `variables`   the ~1250 DISTINCT colours it uses, recoloured for the palette: what a theme
#                   run pushes into open windows (steam-live.py) and bakes into Millennium's
#                   themeColors (steam-colors.py), which is how a restarted Steam has them.
# Measured on the live client: 10310 declarations, 8424 selectors (737 KB of selector text), but
# 1251 distinct colours — embedding the recoloured literal in every rule made a 1.2 MB sheet that
# changed with every wallpaper.
#
# ── What counts as Steam's, and what each becomes ────────────────────────────
# Only colours in Steam's COOL hues (70°–270°: its greens through its blues) are touched.
#   · saturated and not dark (S ≥ 0.40, L ≥ 0.25) — the accents: hue → the palette accent's hue,
#     saturation scaled to its saturation, lightness kept, so Steam's light/dark tonal steps of one
#     blue stay light/dark steps of the accent
#   · any other tint, down to 3 levels of spread (the navy surfaces, the slate text, near-white input text) — a neutral: by how light it is, onto
#     the same bg→fg ramp as the theme's own greys (steam-colors.ramp), so Steam's native panels
#     sit on the same layers as everything the theme already recolours
#   · greys, and warm colours (red/orange/gold — the semantic ones) — left alone.
# Alpha is kept. Rules come as the browser's CSSOM reports them, so longhands (`border-top-color`,
# not `border`), and are re-emitted under the same @media/@supports/@layer, `!important`.
# ─────────────────────────────────────────────────────────────────────────────
import importlib.util
import json
import os
import re
import time

HERE = os.path.dirname(os.path.abspath(__file__))

COOL = (70.0, 270.0)        # degrees
ACCENT_MIN_S = 0.40
ACCENT_MIN_L = 0.25
TINT_MIN_SPREAD = 3         # RGB levels between the strongest and weakest channel; below it, a grey. The same cut as
                            # steam-scan.js's prefilter — they once disagreed (8 there, HSL saturation here), and the
                            # open Library Filter panel, #212124 and #dfe3e6 text, fell between them

BEGIN = "/* quicktest-steam:begin — generated by steam-accent.py, replaced on every theme run */"
END = "/* quicktest-steam:end */"
_PLACEHOLDER = re.compile("\x01(\\d+)\x01")


def _steam_colors():
    spec = importlib.util.spec_from_file_location("steam_colors", os.path.join(HERE, "steam-colors.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# ── colour maths ─────────────────────────────────────────────────────────────

def rgb_to_hsl(r, g, b):
    r, g, b = r / 255, g / 255, b / 255
    mx, mn = max(r, g, b), min(r, g, b)
    l = (mx + mn) / 2
    if mx == mn:
        return 0.0, 0.0, l
    d = mx - mn
    s = d / (2 - mx - mn) if l > 0.5 else d / (mx + mn)
    if mx == r:
        h = ((g - b) / d) % 6
    elif mx == g:
        h = (b - r) / d + 2
    else:
        h = (r - g) / d + 4
    return h * 60, s, l


def hsl_to_rgb(h, s, l):
    c = (1 - abs(2 * l - 1)) * s
    x = c * (1 - abs((h / 60) % 2 - 1))
    m = l - c / 2
    r, g, b = [(c, x, 0), (x, c, 0), (0, c, x), (0, x, c), (x, 0, c), (c, 0, x)][int(h // 60) % 6]
    return tuple(round((v + m) * 255) for v in (r, g, b))


def family(r, g, b):
    """'accent', 'neutral' or None for one of Steam's literals."""
    h, s, l = rgb_to_hsl(r, g, b)
    if not (COOL[0] <= h <= COOL[1]) or max(r, g, b) - min(r, g, b) < TINT_MIN_SPREAD - 1e-9:
        return None
    return "accent" if s >= ACCENT_MIN_S and l >= ACCENT_MIN_L else "neutral"


def recolor(rgb, accent_hsl, bg, fg, base, sc):
    """The palette colour that replaces `rgb`, or None to leave it."""
    fam = family(*rgb)
    if fam is None:
        return None
    if fam == "accent":
        ah, a_s, _ = accent_hsl
        _, s, l = rgb_to_hsl(*rgb)
        return hsl_to_rgb(ah, min(1.0, a_s * min(1.0, s / 0.85)), l)
    return tuple(round(c) for c in sc.mix(bg, fg, sc.ramp(sc.lightness(rgb), base)))


def _css_color(rgb, a):
    hexs = "#%02x%02x%02x" % tuple(rgb)
    return hexs if a >= 0.999 else "rgba(%d,%d,%d,%s)" % (rgb[0], rgb[1], rgb[2], ("%.3f" % a).rstrip("0").rstrip("."))


# ── the stylesheet, and the variables it reads ───────────────────────────────

def var_name(c):
    """The variable for a scanned colour [r, g, b, a, text]: one per distinct rgba."""
    return "--qs-%02x%02x%02x%02x" % (round(c[0]), round(c[1]), round(c[2]), round(c[3] * 255))


def _classified(rules, accent_hsl, bg, fg, base, sc):
    """{variable: palette colour (r,g,b), alpha} for every distinct colour that is Steam's to change."""
    out = {}
    for r in rules:
        for c in r["c"]:
            name = var_name(c)
            if name not in out:
                new = recolor(tuple(c[:3]), accent_hsl, bg, fg, base, sc)
                out[name] = None if new is None else _css_color(new, c[3])
    return out


def variables(rules, bg, fg, accent, base=0.0):
    """{--qs-…: "#rrggbb" | "rgba(…)"} for the palette. bg/fg/accent are (r,g,b); `base` is the
    anchor steam-colors.derive uses for the main background, so Steam's own surfaces share it."""
    sc = _steam_colors()
    cl = _classified(rules, rgb_to_hsl(*accent), bg, fg, base, sc)
    return {k: v for k, v in cl.items() if v is not None}


def rules_css(rules):
    """The static stylesheet. Same rules → same text, whatever the palette.

    A colour that is not Steam's to change (a grey that shared a declaration with a blue) stays
    literal; a declaration where every colour stayed literal is dropped. Selectors whose
    declarations are identical are grouped (8424 selectors made 1336 distinct blocks)."""
    sc = _steam_colors()
    kept = {}
    for r in rules:
        parts, changed = [], False
        for c in r["c"]:
            if family(*c[:3]) is None:
                parts.append(c[4])
            else:
                parts.append("var(%s)" % var_name(c))
                changed = True
        if not changed:
            continue
        value = _PLACEHOLDER.sub(lambda m: parts[int(m.group(1))], r["v"])
        kept.setdefault((tuple(r["w"]), r["s"]), {})[r["p"]] = value
    blocks = {}
    for (w, sel), decls in kept.items():
        body = ";".join("%s:%s!important" % (p, v) for p, v in sorted(decls.items()))
        blocks.setdefault((w, body), []).append(sel)
    tree = {}
    for (w, body), sels in blocks.items():
        tree.setdefault(w, []).append("%s{%s}" % (",".join(sels), body))
    lines = ["/* Steam's own blues, greens and tinted greys, read from variables the shell sets. Generated by steam-accent.py. */"]
    for w, rows in sorted(tree.items()):
        lines.extend(x + "{" for x in w)
        lines.extend(sorted(rows))
        lines.extend("}" for _ in w)
    return "\n".join(lines) + "\n"


# ── Millennium's Quick CSS ───────────────────────────────────────────────────
# ~/.config/millennium/quick.css is injected into every window as it loads, which is how a
# restarted Steam (or a window opened later) gets the override with no debug port. The user's
# own Quick CSS lives in the same file, so ours is a marked block and nothing else is touched.

def merge_quickcss(existing, css):
    """`existing` with our block replaced (or appended); the rest byte for byte."""
    block = BEGIN + "\n" + css.rstrip("\n") + "\n" + END
    a, b = existing.find(BEGIN), existing.find(END)
    if a != -1 and b != -1 and b > a:
        return existing[:a] + block + existing[b + len(END):]
    sep = "" if not existing or existing.endswith("\n") else "\n"
    return existing + sep + ("\n" if existing else "") + block + "\n"


def strip_quickcss(existing):
    a, b = existing.find(BEGIN), existing.find(END)
    if a == -1 or b == -1 or b < a:
        return existing
    return (existing[:a].rstrip("\n") + "\n" + existing[b + len(END):].lstrip("\n")).lstrip("\n")


def write_quickcss(path, css):
    """Atomically put our block into Quick CSS. True when the file changed."""
    try:
        with open(path, encoding="utf-8") as f:
            old = f.read()
    except FileNotFoundError:
        old = ""
    new = merge_quickcss(old, css)
    if new == old:
        return False
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(new)
    os.replace(tmp, path)
    return True


# ── The scan cache ───────────────────────────────────────────────────────────
# Scanning Steam's stylesheets needs a running Steam with its debug port, so the result is
# kept: {"v": 1, "sig": rule count of the main window when scanned, "rules": […]}. Every theme
# run renders from it; a rescan is only needed when Steam's stylesheets change.

def cache_path():
    state = os.environ.get("XDG_STATE_HOME") or os.path.expanduser("~/.local/state")
    return os.path.join(state, "quicktest", "steam-accent-rules.json")


def load_cache():
    try:
        with open(cache_path(), encoding="utf-8") as f:
            data = json.load(f)
        return data if data.get("v") == 1 and isinstance(data.get("rules"), list) else None
    except (OSError, ValueError):
        return None


def save_cache(sig, rules):
    path = cache_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump({"v": 1, "sig": sig, "at": int(time.time()), "rules": rules}, f, separators=(",", ":"))
    os.replace(tmp, path)
